"""Core data models for RAG pipelines."""

from __future__ import annotations

import uuid
from typing import Any, Optional
from pydantic import BaseModel, ConfigDict, Field

from common_framework.core.llm import TokenUsage


class Document(BaseModel):
    """Represents a text document or chunk with associated metadata and vector embedding."""

    model_config = ConfigDict(extra="ignore")

    id: str = Field(default_factory=lambda: str(uuid.uuid4()))
    content: str
    metadata: dict[str, Any] = Field(default_factory=dict)
    embedding: Optional[list[float]] = None

    def __repr__(self) -> str:
        snippet = (self.content[:40] + "...") if len(self.content) > 40 else self.content
        return f"<Document id={self.id!r} content={snippet!r} metadata={self.metadata}>"


class SearchResult(BaseModel):
    """Result of a vector similarity or semantic search query."""

    document: Document
    score: float = Field(ge=0.0, le=1.0, description="Cosine similarity score (0.0 to 1.0)")

    def __repr__(self) -> str:
        return f"<SearchResult score={self.score:.4f} doc_id={self.document.id!r}>"


class RAGResponse(BaseModel):
    """Synthesized response generated by the RAG Engine."""

    answer: str
    sources: list[SearchResult] = Field(default_factory=list)
    model: str
    usage: TokenUsage = Field(default_factory=TokenUsage)
